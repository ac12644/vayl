"""Plain HTTP routes for Vayl's tools, mounted by vayl-server under `/v1` behind the same auth as `/mcp`.

`POST /v1/tools/{name}` takes the tool's arguments as a JSON object and returns `{"result": "..."}`;
`GET /v1/tools` lists the tools with their input schemas. Calls go through FastMCP's `call_tool`, so
argument validation, the capability and scope checks in `_guard`, auditing and metrics are exactly
those of an MCP `tools/call`. The point is a normal REST surface: curl without JSON-RPC or SSE, and an
OpenAPI spec with one typed operation per tool (generated by `vayl.api.openapi`)."""
import json

from fastmcp.exceptions import NotFoundError, ValidationError
from starlette.applications import Starlette
from starlette.responses import JSONResponse
from starlette.routing import Route

from vayl.api import mcp_server

# _deny's tool-result prefix. A denial is an HTTP 403 here; over MCP it stays a normal tool result.
_DENIED = "Access denied:"


def _text(result):
    return "\n".join(c.text for c in result.content if getattr(c, "type", "") == "text")


async def list_tools(request):
    tools = await mcp_server.mcp.list_tools()
    return JSONResponse({"tools": [{"name": t.name, "title": t.annotations.title if t.annotations else None,
                                    "description": t.description, "input_schema": t.parameters}
                                   for t in sorted(tools, key=lambda t: t.name)]})


async def call_tool(request):
    name = request.path_params["name"]
    try:
        args = json.loads(await request.body() or b"{}")
    except ValueError:
        return JSONResponse({"error": "body must be a JSON object of tool arguments"}, status_code=400)
    if not isinstance(args, dict):
        return JSONResponse({"error": "body must be a JSON object of tool arguments"}, status_code=400)
    try:
        result = await mcp_server.mcp.call_tool(name, args)
    except NotFoundError:
        return JSONResponse({"error": f"unknown tool '{name}'; GET /v1/tools lists them"}, status_code=404)
    except ValidationError as e:
        # pydantic's message names the bad argument and why; it echoes the input, which is the caller's own
        return JSONResponse({"error": "invalid arguments", "detail": str(e).split("\n    For further")[0]},
                            status_code=422)
    text = _text(result)
    return JSONResponse({"result": text}, status_code=403 if text.startswith(_DENIED) else 200)


def app():
    return Starlette(routes=[
        Route("/tools", list_tools, methods=["GET"]),
        Route("/tools/{name}", call_tool, methods=["POST"]),
    ])
